alter table public.profiles
add column if not exists points integer not null default 0;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'profiles_points_nonnegative'
  ) then
    alter table public.profiles
    add constraint profiles_points_nonnegative
    check (points >= 0);
  end if;
end $$;


-- ------------------------------------------------------------
-- 2. ARTICLES DE BOUTIQUE
-- ------------------------------------------------------------

create table if not exists public.shop_items (
  id bigint generated by default as identity primary key,
  item_type text not null
    check (item_type in ('booster','miracle','card')),
  title text,
  card_id bigint references public.cards(id) on delete cascade,
  price integer not null check (price > 0),
  stock integer,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint shop_item_shape check (
    (
      item_type = 'booster'
      and card_id is null
      and stock is null
    )
    or
    (
      item_type = 'miracle'
      and card_id is null
      and stock is not null
      and stock >= 0
    )
    or
    (
      item_type = 'card'
      and card_id is not null
      and stock is not null
      and stock >= 0
    )
  )
);

create unique index if not exists shop_one_booster
on public.shop_items(item_type)
where item_type = 'booster';

create unique index if not exists shop_one_miracle
on public.shop_items(item_type)
where item_type = 'miracle';

create unique index if not exists shop_one_listing_per_card
on public.shop_items(card_id)
where item_type = 'card';


-- Historique des achats.
create table if not exists public.shop_purchases (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  item_id bigint references public.shop_items(id) on delete set null,
  item_type text not null,
  card_id bigint references public.cards(id) on delete set null,
  price_paid integer not null,
  purchased_at timestamptz not null default now()
);

create index if not exists shop_purchases_user_idx
on public.shop_purchases(user_id, purchased_at desc);


